// test-0016a.js — L2 part a. Run from repo root:  node tests/test-0016a.js
// Uses the repo's playwright + system Chrome. Network is stubbed (no real Sheet writes).
const path = require('path');
const { chromium } = require('playwright');
(async () => {
  let b;
  try { b = await chromium.launch({ channel: 'chrome' }); } catch (e) { b = await chromium.launch(); }
  const p = await b.newPage();
  const errs = [];
  p.on('pageerror', e => errs.push(e.message));
  p.on('console', m => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
  await p.route('**/*', r => r.request().url().startsWith('file:') ? r.continue()
    : r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ ok: true, token: 'tok', state: null, states: [] }) }));
  await p.goto(('file:///' + path.resolve('index.html').replace(/\\/g, '/')).replace(/#/g, '%23'));
  await p.waitForTimeout(800);
  const R = await p.evaluate(async () => {
    const t = []; const ok = (id, cond, info) => t.push([id, !!cond, info === undefined ? '' : String(info)]);
    window.confirm = () => true;
    const bMeta = document.querySelector('meta[name="build-version"]');
    const bStamp = bMeta ? bMeta.getAttribute('content') : '';
    const bvEl = document.getElementById('buildVer');
    const bvText = bvEl ? bvEl.textContent : '';
    ok('T01 build stamp', /^\d{8}\.\d{4}$/.test(bStamp) && document.title.indexOf(bStamp) > 0 && bvText.indexOf(bStamp) > 0, bStamp);
    ok('T02 shiftDateStr month/leap/year', shiftDateStr('01/11/2569', -1) === '31/10/2569' && shiftDateStr('01/03/2567', -1) === '29/02/2567' && shiftDateStr('31/12/2569', 1) === '01/01/2570');
    localStorage.clear();
    const br = 'SBR-01', T = todayISO(), d = n => shiftDateStr(T, n);
    const mk = ds => { const s = newState(br); s.date = ds; return s; };
    const c6 = mk(d(-6)); c6.stock.ORI.received_pieces = 100; c6.stock.ORI.fry_out = 30; c6.is_closed = true;
    localStorage.setItem(stateKey(br, d(-6)), JSON.stringify(c6));
    const a4 = mk(d(-4)); a4.sales = [{ ts: 'x', totalAmount: 50, totalPieces: 2, items: [] }];
    localStorage.setItem(stateKey(br, d(-4)), JSON.stringify(a4));
    localStorage.setItem(stateKey(br, d(-3)), JSON.stringify(mk(d(-3))));
    localStorage.setItem('puff10_loginStaff', JSON.stringify({ name: 'Test', nick: 'T', phone: '0' }));
    document.getElementById('loginScreen').style.display = 'none'; document.getElementById('mainApp').style.display = 'block';
    setBranch(br); go('home');
    const todayRaw = localStorage.getItem(stateKey(br, T));
    const c = backDateCandidates();
    ok('T03 candidates = 5 days after last closed (-5..-1)', c.length === 5 && c[0].date === d(-5) && c[4].date === d(-1), c.map(x => x.date).join(','));
    ok('T04 -5 and -4 selectable, -3..-1 blocked by -4', !c[0].blockedBy && !c[1].blockedBy && c[1].active && c[2].blockedBy === d(-4) && c[4].blockedBy === d(-4));
    go('close');
    ok('T05 owner branch entry shows HQ PIN field', !!document.querySelector('#backDateEntry input[type=password]'));
    ok('T06 3 blocked day buttons disabled', document.querySelectorAll('#backDateEntry button[disabled]').length === 3);
    enterBackDate(d(-3), 'test reason');
    ok('T07 enterBackDate refuses a blocked day', _backDate === null);
    enterBackDate(d(-5), 'test reason');
    ok('T08 mode full on -5', _backDate && _backDate.date === d(-5) && _backDate.scope === 'full');
    ok('T09 S.date = back day (not today)', S.date === d(-5), S.date);
    ok('T10 carry from last closed day (100-30=70)', S.stock.ORI.received_pieces === 70, S.stock.ORI.received_pieces);
    ok('T11 reason logged in state', S.backdate_log && S.backdate_log[0].reason === 'test reason');
    ok('T12 back day saved under its own key', !!localStorage.getItem(stateKey(br, d(-5))));
    ok('T13 today key untouched', localStorage.getItem(stateKey(br, T)) === todayRaw);
    const bar = document.getElementById('backDateBanner');
    ok('T14 banner visible with date', getComputedStyle(bar).display === 'flex' && bar.textContent.indexOf(d(-5)) >= 0, bar.textContent);
    go('sell'); go('stock'); go('home');
    ok('T15 tab switching keeps back day', S.date === d(-5) && getComputedStyle(bar).display === 'flex');
    ok('T25 Home hero labelled with back day', (document.getElementById('homeSalesCard').textContent || '').indexOf(d(-5)) >= 0);
    ok('T26 date strip hidden while back day open', document.getElementById('homeDateStrip').children.length === 0);
    ok('T16 entryTs carries back day', entryTs().indexOf(d(-5) + ' ') === 0, entryTs());
    refreshFromCloud();
    ok('T17 app re-open refresh does not swap S', S.date === d(-5));
    exitBackDate();
    ok('T18 exit -> today, banner hidden', _backDate === null && S.date === T && getComputedStyle(bar).display === 'none');
    ok('T19 entryTs back to today', entryTs().indexOf(d(-5)) === -1);
    enterPastDayClose(d(-4)); go('sell');
    ok('T20 Issue3 close-scope: other tabs locked', currentTab === 'close' && S.date === d(-4));
    go('home');
    ok('T21 Issue3 close-scope: Home locked too (old wrong-day-close bug)', currentTab === 'close' && S.date === d(-4));
    restoreToday();
    ok('T22 restoreToday clears mode', _backDate === null && currentTab === 'home');
    ok('T23 preview of a missing past day keys to that day', loadBranch(br, d(-2)).date === d(-2));
    const pg = document.getElementById('page-hq'); clr(pg); renderHQEnterPin(pg);
    pg.querySelector('input').value = '1234'; pg.querySelector('button').onclick();
    await new Promise(r => setTimeout(r, 400));
    ok('T24 HQ tab login still works via hqAuth()', !!localStorage.getItem('puff10_hqSession') && localStorage.getItem('puff10_hqToken') === 'tok');
    localStorage.clear();
    return t;
  });
  let pass = 0;
  R.forEach(r => { console.log((r[1] ? 'PASS ' : 'FAIL ') + r[0] + (r[2] ? '  [' + r[2] + ']' : '')); if (r[1]) pass++; });
  console.log('console errors: ' + errs.length + (errs.length ? '\n  ' + errs.join('\n  ') : ''));
  console.log('RESULT ' + pass + '/' + R.length + (pass === R.length && !errs.length ? ' ALL PASS' : ' — NOT PASSING'));
  await b.close();
})();
